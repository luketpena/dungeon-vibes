    /** Clamps [kelvin] to what product [productId] supports; null product uses the default range. */
    fun clampKelvin(productId: Int?, kelvin: Int): Int {
        if (productId == null) return kelvin.coerceIn(DEFAULT_MIN_KELVIN, DEFAULT_MAX_KELVIN)
        val index = Arrays.binarySearch(productIds, productId)
        if (index < 0) return kelvin.coerceIn(DEFAULT_MIN_KELVIN, DEFAULT_MAX_KELVIN)
        return kelvin.coerceIn(minKelvin[index], maxKelvin[index])
    }
